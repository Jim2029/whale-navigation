  // 支持的语言列表（UI 下拉用）
  const LANGS = [
    { code: 'zh_CN', label: '简体中文' },
    { code: 'en',    label: 'English' },
    { code: 'ja',    label: '日本語' },
    { code: 'ko',    label: '한국어' },
    { code: 'es',    label: 'Español' },
    { code: 'ar',    label: 'العربية' },
    { code: 'id',    label: 'Bahasa Indonesia' }
  ];

  // UI 语言状态
  let currentLang = 'zh_CN';

  // chrome.i18n.getUILanguage() 返回的 code -> 我们的目录 code
  function normalizeUILanguage(uiLang) {
    if (!uiLang) return 'zh_CN';
    const s = String(uiLang).replace('_', '-').toLowerCase();
    if (s.startsWith('zh')) return 'zh_CN';
    if (s.startsWith('en')) return 'en';
    if (s.startsWith('ja')) return 'ja';
    if (s.startsWith('ko')) return 'ko';
    if (s.startsWith('es')) return 'es';
    if (s.startsWith('ar')) return 'ar';
    if (s.startsWith('id') || s.startsWith('ms')) return 'id';  // ms -> id 兜底
    return 'zh_CN';
  }

  function resolveBrowserLang() {
    try {
      if (typeof chrome !== 'undefined' && chrome.i18n && chrome.i18n.getUILanguage) {
        return normalizeUILanguage(chrome.i18n.getUILanguage());
      }
    } catch (e) { /* ignore */ }
    if (typeof navigator !== 'undefined' && navigator.language) {
      return normalizeUILanguage(navigator.language);
    }
    return 'zh_CN';
  }

  // 取原始条目（appName/appDesc 是 {message:'...'} 包装，其余是字符串）
  function rawEntry(lang, key) {
    const dict = LANG_DICT[lang] || LANG_DICT['zh_CN'];
    const v = dict[key];
    if (v == null) return null;
    if (typeof v === 'object' && 'message' in v) return v.message;
    return v;
  }

  // t(key, params={}) —— 翻译 + 占位符替换
  function t(key, params) {
    params = params || {};
    let str = rawEntry(currentLang, key);
    if (str == null) str = rawEntry('zh_CN', key);
    if (str == null) return key;
    // 替换 {xxx} 命名占位符
    return String(str).replace(/\{(\w+)\}/g, function (_, name) {
      return (name in params) ? String(params[name]) : '{' + name + '}';
    });
  }

  // 把当前语言写入 <html lang>（始终 LTR，不镜像布局）
  function applyDir() {
    try {
      const html = document.documentElement;
      html.setAttribute('lang', currentLang.replace('_', '-'));
      html.setAttribute('dir', 'ltr');  // 固定 LTR，避免 sidebar 跑到右边
    } catch (e) { /* no document */ }
  }

  // applyI18n() —— 扫描 data-i18n* 属性
  function applyI18n(root) {
    const scope = root || document;
    try {
      scope.querySelectorAll('[data-i18n]').forEach(function (el) {
        const k = el.getAttribute('data-i18n');
        if (k) el.textContent = t(k);
      });
      scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
        const k = el.getAttribute('data-i18n-placeholder');
        if (k) el.setAttribute('placeholder', t(k));
      });
      scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
        const k = el.getAttribute('data-i18n-title');
        if (k) el.setAttribute('title', t(k));
      });
      scope.querySelectorAll('[data-i18n-html]').forEach(function (el) {
        const k = el.getAttribute('data-i18n-html');
        if (k) el.innerHTML = t(k);
      });
      applyDir();
    } catch (e) { /* no document */ }
  }

  // setLanguage(code) —— 写入 storage 并重新 apply
  function setLanguage(code) {
    if (!LANG_DICT[code]) code = 'zh_CN';
    currentLang = code;
    try {
      if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
        chrome.storage.local.set({ uiLanguage: code });
      }
    } catch (e) { /* ignore */ }
    applyI18n();
    return code;
  }

  function getLanguage() { return currentLang; }

  // 初始化：优先 storage，其次浏览器语言
  function init() {
    return new Promise(function (resolve) {
      let stored = null;
      try {
        if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
          chrome.storage.local.get('uiLanguage', function (obj) {
            stored = (obj && obj.uiLanguage) || null;
            currentLang = (stored && LANG_DICT[stored]) ? stored : resolveBrowserLang();
            applyI18n();
            resolve(currentLang);
          });
          return;
        }
      } catch (e) { /* fallthrough */ }
      currentLang = resolveBrowserLang();
      applyI18n();
      resolve(currentLang);
    });
  }

